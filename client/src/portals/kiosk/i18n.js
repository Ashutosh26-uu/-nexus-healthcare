export function makeT(code) {
  const table = STR[code] || STR.en;
  return (key, vars) => {
    let s = table[key] ?? STR.en[key] ?? key;
    if (vars && typeof s === 'string') Object.entries(vars).forEach(([k, v]) => { s = s.replace(`{${k}}`, v); });
    return s;
  };
}

export const hasFullCopy = (code) => Boolean(STR[code]);
